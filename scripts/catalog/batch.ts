/**
 * C-071: turns scripts/catalog/candidates.json (discover.ts) into an idempotent SQL migration
 * that adds the target cities and each city's top `perCity` hotels.
 *
 *   node scripts/catalog/batch.ts 3 [city[:n] …] > supabase/migrations/<version>_catalog_batch.sql
 *
 * Without cities every city gets its top 3; `abu-dhabi:5` gives one city its own number.
 *
 * Rank within a city = how luxurious the hotel is: Tripadvisor's typical minimum nightly price,
 * highest first, among hotels with at least MIN_REVIEWS reviews (established, real five-star
 * hotels rather than new or misfiled ones). Hotels we already have count towards `perCity`:
 * `on conflict do nothing` skips them by slug or Tripadvisor key, and never deletes or deactivates.
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { CITIES, type Candidate } from './discover.ts';

const DIR = dirname(fileURLToPath(import.meta.url));
export const MIN_REVIEWS = 200;

const slugPart = (s: string) =>
  s
    .toLowerCase()
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .replace(/ß/g, 'ss')
    .replace(/&/g, ' and ')
    .replace(/'/g, '')
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '');

/**
 * `name` + city slug, unless the name already says where (in the slug's or another spelling:
 * "Raffles Singapore" → `raffles-singapore`, not `raffles-singapore-singapur`).
 */
export function slugify(name: string, city: string, otherNames: readonly string[] = []): string {
  const base = slugPart(name);
  const has = (c: string) =>
    base === c || base.endsWith(`-${c}`) || base.includes(`-${c}-`) || base.startsWith(`${c}-`);
  return [city, ...otherNames.map(slugPart)].some(has) ? base : `${base}-${city}`;
}

const BRAND_SUFFIX =
  /,\s*(?:an?\s+)?[^,]*\b(?:collection|hotels|member|leading|autograph|curio|oetker|rosewood hotel|by hilton|by ihg|by marriott|by hyatt)\b[^,]*$/i;

/**
 * Display name: Tripadvisor names carry brand suffixes ("Le Bristol Paris, Oetker Hotels",
 * "… Resort By IHG") and trailing city names after a comma ("Ritz-Carlton, Berlin"). The city
 * stays when the rest would be a bare brand ("Mandarin Oriental, Munich" → "Mandarin Oriental
 * Munich").
 */
export function cleanName(name: string, cityNames: readonly string[]): string {
  let n = name.trim().replace(/\s+by\s+(IHG|Hilton|Marriott|Hyatt|Accor|Wyndham)$/i, '');
  let city = '';
  for (let i = 0; i < 3; i++) {
    n = n.replace(BRAND_SUFFIX, '').trim();
    const m = /^(.*),\s*([^,]+)$/.exec(n);
    if (m?.[1] && m[2] && cityNames.some((c) => c.toLowerCase() === m[2]?.trim().toLowerCase())) {
      n = m[1].trim();
      city = m[2].trim();
    }
  }
  return city && n.split(/\s+/).length <= 2 ? `${n} ${city}` : n;
}

/** The city's hotels in rank order (see the file comment). */
export function ranked(list: readonly Candidate[]): Candidate[] {
  return list
    .filter((c) => c.taReviews >= MIN_REVIEWS && c.priceMin !== null)
    .sort((a, b) => (b.priceMin ?? 0) - (a.priceMin ?? 0) || b.taReviews - a.taReviews);
}

const q = (s: string) => `'${s.replace(/'/g, "''")}'`;

export function batchSql(
  all: Record<string, Candidate[]>,
  perCity: number,
  /** Cities that get hotels in this batch, `slug` or `slug:n` (all when empty). */
  only: readonly string[] = [],
): string {
  const counts = new Map(
    only.map((o) => {
      const [slug = '', n] = o.split(':');
      return [slug, n === undefined ? perCity : Number(n)] as const;
    }),
  );
  const cities = CITIES.map(
    (c) => `  (${q(c.slug)}, ${q(c.nameDe)}, ${q(c.nameEn)}, ${q(c.countryCode)})`,
  );
  const hotels: string[] = [];
  for (const c of CITIES) {
    if (only.length && !counts.has(c.slug)) continue;
    for (const h of ranked(all[c.slug] ?? []).slice(0, counts.get(c.slug) ?? perCity)) {
      const name = cleanName(h.name, [c.nameEn, c.nameDe, ...c.liteCities]);
      hotels.push(
        `  (${q(slugify(name, c.slug, [c.nameEn, c.nameDe]))}, ${q(name)}, ${q(c.slug)}, ${h.lat}, ${h.lng}, ${q(h.xoteloKey)}, ${h.liteapiId ? q(h.liteapiId) : 'null'})`,
      );
    }
  }
  return `-- C-071 catalog batch: the target cities (D-43) and the top five-star hotels of
-- ${only.length ? only.join(', ') : `every city (${perCity} each)`}
-- by Tripadvisor's typical minimum price (generated by scripts/catalog/batch.ts from
-- candidates.json). Idempotent: existing cities and hotels (same slug or Tripadvisor key) stay
-- as they are.

alter table public.hotels add column if not exists liteapi_id text unique;

insert into public.cities (slug, name_de, name_en, country_code)
values
${cities.join(',\n')}
on conflict (slug) do nothing;

insert into public.hotels (slug, name, city_id, lat, lng, xotelo_key, liteapi_id, active)
select v.slug, v.name, c.id, v.lat, v.lng, v.xotelo_key, v.liteapi_id, true
from (values
${hotels.join(',\n')}
) as v (slug, name, city, lat, lng, xotelo_key, liteapi_id)
join public.cities c on c.slug = v.city
on conflict do nothing;
`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const perCity = Number(process.argv[2] ?? 3);
  const all = JSON.parse(readFileSync(join(DIR, 'candidates.json'), 'utf8')) as Record<
    string,
    Candidate[]
  >;
  process.stdout.write(batchSql(all, perCity, process.argv.slice(3)));
}
