/**
 * C-011b: turns scripts/catalog/photos.json (from photos.ts, run in GitHub Actions) into SQL that
 * sets `hotels.image_url` and `image_credit`. Hotels without a licensed photo keep null
 * (the UI shows a gradient). Apply it as a migration (README → Database).
 *   node scripts/catalog/photos-sql.ts > /tmp/photos.sql
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = dirname(fileURLToPath(import.meta.url));

interface Photo {
  slug: string;
  imageUrl: string | null;
  credit: string | null;
  pageUrl: string | null;
}

const sqlString = (v: string): string => `'${v.replace(/'/g, "''")}'`;

const photos: Photo[] = JSON.parse(readFileSync(join(DIR, 'photos.json'), 'utf8'));
const found = photos.filter(
  (p): p is Photo & { imageUrl: string; credit: string } =>
    /^https:\/\/(upload|thumb)\.wikimedia\.org\/[^?#]+$/.test(p.imageUrl ?? '') && !!p.credit,
);

console.log(
  '-- Hotel photos (C-011b), generated by scripts/catalog/photos-sql.ts from photos.json.',
);
console.log(
  '-- Licensed Wikimedia Commons images (CC BY, CC BY-SA, CC0, public domain) with credits.',
);
console.log(
  '-- image_source_url: the Commons file page, linked from the credit (CC BY/BY-SA attribution).',
);
console.log('alter table public.hotels add column if not exists image_source_url text;');
if (found.length === 0) {
  console.log('select 1; -- no photos found');
} else {
  console.log('update public.hotels h');
  console.log(
    'set image_url = v.image_url, image_credit = v.image_credit, image_source_url = v.image_source_url',
  );
  console.log('from (values');
  console.log(
    found
      .map(
        (p) =>
          `  (${sqlString(p.slug)}, ${sqlString(p.imageUrl)}, ${sqlString(p.credit)}, ${p.pageUrl ? sqlString(p.pageUrl) : 'null'})`,
      )
      .join(',\n'),
  );
  console.log(') as v (slug, image_url, image_credit, image_source_url)');
  console.log('where h.slug = v.slug;');
}
console.error(`${found.length} of ${photos.length} hotels get a photo.`);
