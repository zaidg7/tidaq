/**
 * C-011: turns scripts/catalog/resolved.json into an idempotent SQL upsert for `hotels`.
 *   node scripts/catalog/to-sql.ts > /tmp/hotels.sql
 * Apply it as a migration (README → Database). Re-running updates names, identifiers and
 * coordinates by slug and never deletes. Hotels listed in INACTIVE start with active = false
 * (budget, D-13: 36 active hotels × 8 stays ≈ 290 tasks/day).
 */
import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = dirname(fileURLToPath(import.meta.url));

interface Resolved {
  slug: string;
  name: string;
  city: string;
  dfsHotelIdentifier: string | null;
  lat: number | null;
  lng: number | null;
}

/** The 4th hotel in the four 4-hotel cities: resolved and ready, switched on when budget allows. */
export const INACTIVE = new Set([
  'hotel-de-rome-berlin',
  'the-charles-hotel-muenchen',
  'the-westin-hamburg',
  'hotel-imperial-wien',
]);

const sqlString = (v: string | null): string =>
  v === null ? 'null' : `'${v.replace(/'/g, "''")}'`;
const sqlNumber = (v: number | null): string =>
  v === null ? 'null' : String(Math.round(v * 1e6) / 1e6);

const hotels: Resolved[] = JSON.parse(readFileSync(join(DIR, 'resolved.json'), 'utf8'));
const missing = hotels.filter((h) => !h.dfsHotelIdentifier);
if (missing.length > 0) {
  console.error(`Unresolved hotels (not exported): ${missing.map((h) => h.slug).join(', ')}`);
}

const rows = hotels
  .filter((h) => h.dfsHotelIdentifier)
  .map(
    (h) =>
      `  (${sqlString(h.slug)}, ${sqlString(h.name)}, ${sqlString(h.city)}, ${sqlString(h.dfsHotelIdentifier)}, ${sqlNumber(h.lat)}, ${sqlNumber(h.lng)}, ${!INACTIVE.has(h.slug)})`,
  );

console.log(`-- Hotel catalog (C-011), generated by scripts/catalog/to-sql.ts from resolved.json.
-- Idempotent: upsert by slug. Identifiers come from DataForSEO Hotel Searches (12 Oct 2026).
insert into public.hotels (slug, name, city_id, dfs_hotel_identifier, lat, lng, active)
select v.slug, v.name, c.id, v.dfs_hotel_identifier, v.lat, v.lng, v.active
from (values
${rows.join(',\n')}
) as v (slug, name, city_slug, dfs_hotel_identifier, lat, lng, active)
join public.cities c on c.slug = v.city_slug
on conflict (slug) do update set
  name = excluded.name,
  city_id = excluded.city_id,
  dfs_hotel_identifier = excluded.dfs_hotel_identifier,
  lat = excluded.lat,
  lng = excluded.lng;`);
