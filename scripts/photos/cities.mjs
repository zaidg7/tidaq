// C-105: city photos (Unsplash License: free for commercial use, no permission needed) copied once
// into apps/web/public/cities/<slug>-{480,960,1600}.webp with a 24 px blur placeholder, listed in
// apps/web/lib/cityPhotos.generated.ts. Used for city tiles, city pages, the home hero and as the
// labelled "Stadtbild" fallback for hotels without their own photo (PREMIUM.md §7.1).
//
// Usage: node scripts/photos/cities.mjs   (input: scripts/photos/cities.json)
// images.unsplash.com is reachable from the cloud sessions, so no GitHub runner is needed.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const webRequire = createRequire(join(root, 'apps/web/package.json'));
const sharp = createRequire(webRequire.resolve('next/package.json'))('sharp');
const outDir = join(root, 'apps/web/public/cities');
const WIDTHS = [480, 960, 1600];
const list = JSON.parse(readFileSync(join(root, 'scripts/photos/cities.json'), 'utf8'));
mkdirSync(outDir, { recursive: true });

const manifest = {};
for (const { slug, unsplash, alt, focus } of list) {
  if (!/^[a-z0-9-]+$/.test(slug) || !/^[0-9]+-[0-9a-f]+$/.test(unsplash)) {
    throw new Error(`bad entry ${slug}`);
  }
  const res = await fetch(`https://images.unsplash.com/photo-${unsplash}?w=2400&q=85&fm=jpg`);
  if (!res.ok) throw new Error(`${slug}: HTTP ${res.status}`);
  const input = Buffer.from(await res.arrayBuffer());
  const entry = { alt, source: `https://unsplash.com/photos/${unsplash}` };
  for (const width of WIDTHS) {
    const { data, info } = await sharp(input)
      .rotate()
      .resize({ width, height: width, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: width >= 1600 ? 68 : 72 })
      .toBuffer({ resolveWithObject: true });
    writeFileSync(join(outDir, `${slug}-${width}.webp`), data);
    entry[width] = { src: `/cities/${slug}-${width}.webp`, width: info.width, height: info.height };
  }
  const lqip = await sharp(input)
    .resize({ width: 24, height: 24, fit: 'inside' })
    .webp({ quality: 40 })
    .toBuffer();
  entry.lqip = `data:image/webp;base64,${lqip.toString('base64')}`;
  if (focus) entry.focus = focus;
  manifest[slug] = entry;
  console.log(slug, entry[1600].width, 'x', entry[1600].height);
}

const body = Object.entries(manifest)
  .map(([slug, e]) => `  '${slug}': ${JSON.stringify(e)},`)
  .join('\n');
writeFileSync(
  join(root, 'apps/web/lib/cityPhotos.generated.ts'),
  `// Generated by scripts/photos/cities.mjs (C-105). Do not edit by hand.\nimport type { CityPhoto } from './cityPhotos';\n\nexport const CITY_PHOTOS: Record<string, CityPhoto> = {\n${body}\n};\n`,
);
