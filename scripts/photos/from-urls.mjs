// C-125: self-hosts picked hotel photos from direct image URLs (Commons thumbnails or Flickr),
// for when the Wikimedia API is rate-limited (fetch.ts needs it). Same output as fetch.ts:
// `apps/web/public/hotels/<slug>-{160,480,960,1600}.webp`, a 24 px blur placeholder and the focus
// in `apps/web/lib/hotelPhotos.generated.ts`. Credits go to the database by migration.
//
//   node scripts/photos/from-urls.mjs list.json
//
// list.json = [{ "slug": "…", "url": "https://upload.wikimedia.org/…/1920px-….jpg",
//                "focus": "50% 40%" }] (focus optional). A Commons `/1920px-` URL falls back to
// `/1280px-` when the larger size is refused.
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
const webRequire = createRequire(join(ROOT, 'apps/web/package.json'));
const sharp = createRequire(webRequire.resolve('next/package.json'))('sharp');
const UA = 'TidaqPhotoCopy/1.1 (https://tidaq.com; one-time copy of licensed photos)';
const WIDTHS = [160, 480, 960, 1600];
const outDir = join(ROOT, 'apps/web/public/hotels');
const manifestPath = join(ROOT, 'apps/web/lib/hotelPhotos.generated.ts');
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

const manifest = {};
for (const m of readFileSync(manifestPath, 'utf8').matchAll(/^ {2}'([a-z0-9-]+)': (\{.*\}),$/gm)) {
  manifest[m[1]] = JSON.parse(m[2]);
}

for (const p of JSON.parse(readFileSync(process.argv[2], 'utf8'))) {
  if (!/^[a-z0-9-]+$/.test(p.slug)) throw new Error(`bad slug ${p.slug}`);
  const urls = [p.url, p.url.replace('/1920px-', '/1280px-')];
  let input;
  for (let attempt = 0; attempt < 8 && !input; attempt++) {
    const res = await fetch(urls[attempt % 2], { headers: { 'user-agent': UA } });
    if (res.ok) input = Buffer.from(await res.arrayBuffer());
    else await sleep(4000 * (attempt + 1));
  }
  if (!input) throw new Error(`${p.slug}: download failed`);
  const entry = {};
  for (const width of WIDTHS) {
    const { data, info } = await sharp(input)
      .rotate()
      .resize({ width, height: width, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: width <= 160 ? 70 : width >= 1600 ? 68 : 72 })
      .toBuffer({ resolveWithObject: true });
    writeFileSync(join(outDir, `${p.slug}-${width}.webp`), data);
    entry[width] = {
      src: `/hotels/${p.slug}-${width}.webp`,
      width: info.width,
      height: info.height,
    };
  }
  const lqip = await sharp(input)
    .rotate()
    .resize({ width: 24, height: 24, fit: 'inside' })
    .webp({ quality: 40 })
    .toBuffer();
  entry.lqip = `data:image/webp;base64,${lqip.toString('base64')}`;
  if (p.focus) entry.focus = p.focus;
  manifest[p.slug] = entry;
  console.error(`${p.slug}: ${entry[1600].width}×${entry[1600].height}`);
  await sleep(800);
}

const body = Object.entries(manifest)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, e]) => `  '${slug}': ${JSON.stringify(e)},`)
  .join('\n');
writeFileSync(
  manifestPath,
  `// Generated by scripts/photos/fetch.ts (C-104) and self-host.mjs (C-011c). Do not edit by hand.\nimport type { HotelPhoto } from './hotelPhotos';\n\nexport const HOTEL_PHOTOS: Record<string, HotelPhoto> = {\n${body}\n};\n`,
);
