// C-011c: copy each hotel photo once from Wikimedia Commons into apps/web/public/hotels/, so
// pages load photos only from our own domain (no third-party cookies or IP logging, D-15).
//
// Usage: node scripts/photos/self-host.mjs photos.json
// photos.json = [{ "slug": "…", "url": "https://upload.wikimedia.org/…" }, …]
// (export it with: select slug, image_url as url from hotels where image_url is not null)
//
// Writes <slug>-160.webp (thumbnails) and <slug>-960.webp (cards, hotel pages), each fitted
// inside a square of that size and regenerates
// apps/web/lib/hotelPhotos.generated.ts. Re-run when a hotel gets a new photo.
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { createRequire } from 'node:module';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
// sharp ships with Next.js (an optional dependency of next); resolve it through next.
const webRequire = createRequire(join(root, 'apps/web/package.json'));
const sharp = createRequire(webRequire.resolve('next/package.json'))('sharp');
const outDir = join(root, 'apps/web/public/hotels');
const WIDTHS = [160, 960];
const UA = 'TidaqPhotoCopy/1.0 (https://tidaq.com; one-time copy of licensed photos)';

const list = JSON.parse(readFileSync(process.argv[2], 'utf8'));
mkdirSync(outDir, { recursive: true });
// Keep the photos already copied: a run with a few new hotels (C-071c) adds to the manifest.
const manifestPath = join(root, 'apps/web/lib/hotelPhotos.generated.ts');
const { HOTEL_PHOTOS } = await import(pathToFileURL(manifestPath).href);
const manifest = { ...HOTEL_PHOTOS };

for (const { slug, url } of list) {
  if (!/^[a-z0-9-]+$/.test(slug)) throw new Error(`bad slug ${slug}`);
  const res = await fetch(url, { headers: { 'user-agent': UA } });
  if (!res.ok) throw new Error(`${slug}: HTTP ${res.status}`);
  const input = Buffer.from(await res.arrayBuffer());
  const entry = {};
  for (const width of WIDTHS) {
    const { data, info } = await sharp(input)
      .rotate()
      .resize({ width, height: width, fit: 'inside', withoutEnlargement: true })
      .webp({ quality: width <= 160 ? 70 : 72 })
      .toBuffer({ resolveWithObject: true });
    writeFileSync(join(outDir, `${slug}-${width}.webp`), data);
    entry[width] = { src: `/hotels/${slug}-${width}.webp`, width: info.width, height: info.height };
  }
  manifest[slug] = entry;
  console.log(
    slug,
    Object.values(entry)
      .map((e) => `${e.width}x${e.height}`)
      .join(' '),
  );
  await new Promise((r) => setTimeout(r, 500)); // be gentle with Wikimedia
}

const body = Object.entries(manifest)
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([slug, e]) => `  '${slug}': ${JSON.stringify(e)},`)
  .join('\n');
writeFileSync(
  manifestPath,
  `// Generated by scripts/photos/self-host.mjs (C-011c). Do not edit by hand.\nimport type { HotelPhoto } from './hotelPhotos';\n\nexport const HOTEL_PHOTOS: Record<string, HotelPhoto> = {\n${body}\n};\n`,
);
